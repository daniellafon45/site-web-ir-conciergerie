export function getDialCodeByCountryId(id: string): string {
  return DIAL_CODES.find((entry) => entry.id === id)?.code ?? "+1";
}

export function formatDialCodeLabel(entry: DialCodeOption): string {
  return `${entry.code} — ${entry.country}`;
}

export function filterDialCodes(query: string): DialCodeOption[] {
  const q = query.trim().toLowerCase();
  if (!q) return DIAL_CODES;
  return DIAL_CODES.filter(
    (entry) => entry.country.toLowerCase().includes(q) || entry.code.includes(q),
  );
}

export function getDialCodeOptionByCountryId(id: string): DialCodeOption | undefined {
  return DIAL_CODES.find((entry) => entry.id === id);
}
